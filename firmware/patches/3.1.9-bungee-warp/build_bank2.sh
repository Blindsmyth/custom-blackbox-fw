#!/bin/sh
# Build the bank-2 leaf ELF (Bungee Basic + CMSIS FFT) and pack BBEXTRA.BIN (flash image only).
# Needs the Arm GNU Toolchain (ARM_GNU=/path/to/its bin), the Bungee checkout with submodules in
# tools/lab/bungee/bungee and the CMSIS tree in tools/lab/rb/m7/cmsis. Writes bg/bank2_syms.h.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
T=${ARM_GNU:-$HOME/.local/arm-gnu-15.3/bin}
BG="$ROOT/tools/lab/bungee/bungee"
BGM7="$ROOT/tools/lab/bungee/m7"
CMSIS="$ROOT/tools/lab/rb/m7/cmsis"
OUT=${OUT_DIR:-$HERE/out}         # OUT_DIR, SYMS_H, DEFS (-D...): experiment builds
SYMS_H=${SYMS_H:-$HERE/bg/bank2_syms.h}
OBJ="$OUT/obj"
mkdir -p "$OBJ"
B2_ID=${B2_ID:-0x42474E31}   # "BGN1": not RB's id, so a unit holding the RB payload re-pairs

CC="$T/arm-none-eabi-gcc"
CXX="$T/arm-none-eabi-g++"
CPU="-mthumb -mcpu=cortex-m7 -mfpu=fpv5-sp-d16 -mfloat-abi=hard -O2 -ffunction-sections -fdata-sections"
CXXFLAGS="-std=c++20 -fwrapv -fno-exceptions -fno-rtti -fno-threadsafe-statics -DBUNGEE_VISIBILITY= \
  -DBUNGEE_SELF_TEST=0 -DBUNGEE_NO_LOG -Deigen_assert=BUNGEE_ASSERT1 -DEIGEN_DONT_PARALLELIZE=1 \
  -DEIGEN_NO_IO -DBUNGEE_VERSION=\"b2\" -DBG_PRIME_HALVES=${PRIME:-1} $DEFS"
RSP="$OBJ/b2.rsp"
: > "$RSP"

for f in TransformFunctions/arm_rfft_fast_f32 TransformFunctions/arm_rfft_fast_init_f32 \
         TransformFunctions/arm_cfft_f32 TransformFunctions/arm_cfft_init_f32 \
         TransformFunctions/arm_cfft_radix8_f32 TransformFunctions/arm_bitreversal \
         TransformFunctions/arm_bitreversal2 CommonTables/arm_common_tables CommonTables/arm_const_structs; do
    o="$OBJ/$(basename $f).o"
    "$CC" $CPU -DARM_MATH_CM7 -D__FPU_PRESENT=1 -I"$CMSIS/Include" -c -o "$o" "$CMSIS/Source/$f.c"
    printf '"%s"\n' "$o" >> "$RSP"
done
for src in "$BG"/src/*.cpp "$BGM7/Fourier_cmsis.cpp" "$HERE/bg/bg_api.cpp"; do
    [ "$(basename "$src")" = Fourier.cpp ] && continue
    o="$OBJ/bg_$(basename "$src" .cpp).o"
    "$CXX" $CPU $CXXFLAGS -I"$BG" -I"$BG/submodules/eigen" -I"$CMSIS/Include" -I"$HERE/bg" \
        -c -o "$o" "$src"
    printf '"%s"\n' "$o" >> "$RSP"
done
"$CC" $CPU -DB2_ID=$B2_ID -c -o "$OBJ/b2head.o" "$ROOT/firmware/patches/3.1.9-rb-warp/b2/b2head.c"
"$CC" $CPU -c -o "$OBJ/bg_sys.o" "$HERE/bg/bg_sys.c"
printf '"%s"\n"%s"\n' "$OBJ/b2head.o" "$OBJ/bg_sys.o" >> "$RSP"

# Code XIP in bank 2. Mutable state goes in the SRAM4 voice slot past its 64-byte header
# (0x38007040-0x3800E800): SRAM1/2 hold the 3.1.Z slice tables, so RB's SRAM1 placement
# is not free in this image. bg_init copies .data and zeroes .bss every time bank 1
# (re)claims the slot.
cat > "$OUT/bank2_only.ld" <<'EOF'
ENTRY(bg_init)
MEMORY {
  BANK2 (rx) : ORIGIN = 0x08100000, LENGTH = 0xC0000
  VOICE (rw) : ORIGIN = 0x38007040, LENGTH = 0x77C0
}
SECTIONS {
  .b2head : { KEEP(*(.b2head)) } > BANK2
  .text : {
    *(.bank2) *(.text*)
    *(.rodata*)
    . = ALIGN(4);
  } > BANK2
  .ARM.exidx : { __exidx_start = .; *(.ARM.exidx*) __exidx_end = .; } > BANK2
  .data : {
    __data_start = .;
    *(.data*)
    . = ALIGN(4);
    __data_end = .;
  } > VOICE AT > BANK2
  __data_load = LOADADDR(.data);
  .bss (NOLOAD) : {
    __bss_start__ = .;
    *(.bss*) *(COMMON)
    . = ALIGN(4);
    __bss_end__ = .;
    end = .;
  } > VOICE
  /DISCARD/ : { *(.comment .note* .init_array* .fini_array*) }
}
EOF

"$CXX" $CPU -nostartfiles -T "$OUT/bank2_only.ld" -Wl,--gc-sections \
    -Wl,-u,bg_init -Wl,-u,bg_restart -Wl,-u,bg_mix -fno-exceptions -fno-rtti \
    -o "$OUT/bank2.elf" @"$RSP" -lstdc++ -lm -lc -lgcc
"$T/arm-none-eabi-size" -A "$OUT/bank2.elf" | grep -E '^\.(text|data|bss|ARM)'

# Nothing that must not be in bank 2: the EH runtime, stdio, static constructors.
if "$T/arm-none-eabi-nm" "$OUT/bank2.elf" | grep -E ' (__cxa_throw|__cxa_allocate_exception|_Unwind_RaiseException|fprintf|vfprintf|_vfprintf_r|__libc_init_array)$'; then
    echo "bank2.elf links code it must not (above)" >&2
    exit 1
fi

addr() {
    a=$("$T/arm-none-eabi-nm" "$OUT/bank2.elf" | awk -v s="$1" '$3 == s { print $1 }')
    [ -n "$a" ] || { echo "bank2.elf has no $1" >&2; exit 1; }
    printf '0x%08xu' $((0x$a | 1))
}
cat > "$SYMS_H" <<EOF
/* Generated by build_bank2.sh from out/bank2.elf (Thumb addresses). Do not edit. */
#ifndef BANK2_SYMS_H
#define BANK2_SYMS_H
#define BG_INIT_ADDR     $(addr bg_init)
#define BG_RESTART_ADDR  $(addr bg_restart)
#define BG_MIX_ADDR      $(addr bg_mix)
#endif
EOF
cat "$SYMS_H"

python3 "$ROOT/tools/bank2/pack_bbextra.py" "$OUT/bank2.elf" -o "$OUT/BBEXTRA.BIN" --id "$B2_ID"
echo "bank2 ready: $OUT/BBEXTRA.BIN"
